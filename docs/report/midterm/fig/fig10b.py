fig,a=plt.subplots(figsize=(16,9.6)); a.axis("off"); a.set_xlim(0,160); a.set_ylim(0,97)
P={}
def box(k,x,y,w,h,t,c="#ffffff",fs=7.6,bold=False):
    a.add_patch(FancyBboxPatch((x,y),w,h,boxstyle="round,pad=0.25,rounding_size=0.6",fc=c,ec="#444",lw=.9))
    a.text(x+w/2,y+h/2,t,ha="center",va="center",fontsize=fs,weight="bold" if bold else "normal"); P[k]=(x,y,w,h)
def grp(x,y,w,h,t,c):
    a.add_patch(FancyBboxPatch((x,y),w,h,boxstyle="round,pad=0.4",fc=c,ec="#999",ls="--",lw=.8)); a.text(x+0.8,y+h-1.3,t,fontsize=9,weight="bold",va="top")
def ln(p,q,c="#333",ls="-",lw=1.0,arrow=True,t=None,tp=None):
    a.annotate("",q,p,arrowprops=dict(arrowstyle="->" if arrow else "-",color=c,ls=ls,lw=lw,shrinkA=0,shrinkB=0))
    if t: a.text(*(tp or ((p[0]+q[0])/2,(p[1]+q[1])/2+0.8)),t,fontsize=6.8,color=c,ha="center")
def R(k): x,y,w,h=P[k]; return (x+w,y+h/2)
def L(k): x,y,w,h=P[k]; return (x,y+h/2)
def T(k): x,y,w,h=P[k]; return (x+w/2,y+h)
def B(k): x,y,w,h=P[k]; return (x+w/2,y)
