import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Circle
plt.rcParams["font.family"]="Noto Sans CJK JP"
fig,axs=plt.subplots(1,3,figsize=(19,7.2))
C=dict(base="#c9c9c9",frame="#dde6f0",stage="#f2e2c4",fine="#ecd39e",hot="#f6c9b5",head="#e8d9f0",opt="#bfe3d0",sen="#cfe0f5",elec="#eeeeee",ins="#ffffff")
def R(ax,x,y,w,h,c,t="",fs=7.5,ls="-",lw=1):
    ax.add_patch(Rectangle((x,y),w,h,fc=c,ec="#333",lw=lw,ls=ls))
    if t: ax.text(x+w/2,y+h/2,t,ha="center",va="center",fontsize=fs)
def L(ax,x,y,tx,ty,t,fs=7.5):
    ax.annotate(t,(x,y),(tx,ty),fontsize=fs,ha="left",va="center",arrowprops=dict(arrowstyle="-",lw=.6,color="#444"))
def dim(ax,x1,y1,x2,y2,t,off=(0,0)):
    ax.annotate("",(x1,y1),(x2,y2),arrowprops=dict(arrowstyle="<->",lw=.8))
    ax.text((x1+x2)/2+off[0],(y1+y2)/2+off[1],t,ha="center",va="center",fontsize=8,bbox=dict(fc="white",ec="none",pad=1))
